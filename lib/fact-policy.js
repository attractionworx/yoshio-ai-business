// 手動生成・改善・直接生成で共有する方針。真偽の自動判定ではありません。
export const factRule = '元データに存在しない本人の実体験・収益・経歴・成功実績などの事実を推測・創作しないでください。根拠のない数値・URLも捏造せず、不明な事実は「要確認」としてください。具体例は仮の例であることを明示し、本人の経験や実績として書かないでください。';

export function hasClearFactViolation(content) {
  const text = Object.values(content).flat().join('\n');
  // 限定した明確な断定のみを検出。通過しても事実確認済みとは扱いません。
  return /(?:私は|僕は|筆者は|私の|筆者の|私が|僕が)[^。\n]{0,60}(?:稼ぎました|稼いだ|収益は?\s*[\d０-９]|月収\s*[\d０-９]|年収\s*[\d０-９]|勤務していました|勤務しました|卒業しました|受賞しました|達成しました|経験しました|経営しています)/u.test(text)
    || /(?:必ず|確実に)[^。\n]{0,30}(?:稼げ|儲か|収益|成功)/u.test(text)
    || text.split(/[。\n]/u).some(sentence => !/要確認|仮の例|仮定/u.test(sentence) && (
      /https?:\/\//iu.test(sentence)
      || /(?:収益|年収|月収|成功率|売上|利益)(?:は|が|：|:)?\s*[\d０-９][\d０-９,.，．]*\s*(?:万|億)?(?:円|%|％)/u.test(sentence)
    ));
}
